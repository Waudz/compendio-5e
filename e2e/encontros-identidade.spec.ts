import { test, expect, navigate, campaignName, expectNoHorizontalOverflow } from './fixtures';

test('cinco goblins: líder individual, envio 4+1 e reinserção ferida persistente', async ({ page }, info) => {
  await page.goto('?demo=mestre&nuvem=1');
  await expect(page.getByRole('heading', { name: campaignName, exact: true })).toBeVisible();
  await navigate(page, 'Encontros');
  await page.getByLabel('Nome do encontro', { exact: true }).fill('QA cinco goblins');
  await page.getByRole('button', { name: 'Criar encontro', exact: true }).click();
  const encontro = page.getByRole('region', { name: 'Página do encontro QA cinco goblins' });
  const form = encontro.getByRole('form', { name: 'Adicionar participante a QA cinco goblins' });
  await form.getByLabel('Nome', { exact: true }).fill('Goblin');
  await form.getByLabel('Quantidade', { exact: true }).fill('5');
  await form.getByLabel('PV de cada (opcional)', { exact: true }).fill('7');
  await form.getByLabel('CA (opcional)', { exact: true }).fill('15');
  await form.getByRole('button', { name: 'Adicionar', exact: true }).click();
  await encontro.getByRole('button', { name: 'Personalizar indivíduos (5)', exact: true }).click();
  const terceiro = encontro.locator('.enc-instancia').nth(2);
  await terceiro.getByRole('button', { name: 'Personalizar Goblin 3', exact: true }).click();
  await terceiro.getByLabel('Nome individual', { exact: true }).fill('Líder goblin');
  await terceiro.getByLabel('PV individual', { exact: true }).fill('20');
  await terceiro.getByLabel('CA individual', { exact: true }).fill('17');
  await terceiro.getByLabel('Notas individuais', { exact: true }).fill('Chave da fortaleza');
  await terceiro.getByRole('button', { name: 'Salvar personalização', exact: true }).click();
  await encontro.getByRole('button', { name: 'Enviar só parte para a Iniciativa', exact: true }).click();
  let dialogo = page.getByRole('dialog', { name: 'Enviar só parte para a Iniciativa', exact: true });
  await dialogo.getByText('Escolher criaturas específicas', { exact: true }).click();
  await dialogo.getByRole('checkbox', { name: 'Goblin 5 · PV 7/7 · CA 15', exact: true }).uncheck();
  await dialogo.getByRole('button', { name: 'Incluir no combate: QA cinco goblins', exact: true }).click();
  await navigate(page, 'Iniciativa');
  const combatentes = page.getByRole('group', { name: 'Combatentes', exact: true });
  await expect(combatentes.locator('.ini-item')).toHaveCount(4);
  await expect(page.getByLabel('PV de Líder goblin', { exact: true })).toHaveText('PV 20/20');
  const enviar = async () => {
    await page.getByRole('button', { name: 'Encontros preparados', exact: true }).click();
    await page.getByLabel('Buscar combatentes', { exact: true }).fill('QA cinco goblins');
    await page.getByRole('button', { name: 'Selecionar encontro QA cinco goblins', exact: true }).click();
    const d = page.getByRole('dialog', { name: 'Adicionar encontro preparado', exact: true });
    await d.getByRole('button', { name: 'Incluir no combate: QA cinco goblins', exact: true }).click();
  };
  await enviar(); await expect(combatentes.locator('.ini-item')).toHaveCount(5);
  await page.getByLabel('Quantidade de dano ou cura de Goblin 2', { exact: true }).fill('3');
  await page.getByRole('button', { name: 'Causar dano a Goblin 2', exact: true }).click();
  await expect(page.getByLabel('Quantidade de dano ou cura de Goblin 2', { exact: true })).toHaveValue('1');
  await expect(page.getByLabel('PV de Goblin 2', { exact: true })).toHaveText('PV 4/7');
  await page.getByRole('button', { name: 'Remover Goblin 2', exact: true }).click();
  await expect(combatentes.locator('.ini-item')).toHaveCount(4); await enviar();
  await expect(combatentes.locator('.ini-item')).toHaveCount(5);
  await expect(page.getByLabel('PV de Goblin 2', { exact: true })).toHaveText('PV 4/7');
  const nomes = await combatentes.locator('.ini-nome strong').allTextContents();
  await page.getByRole('button', { name: 'Próximo turno', exact: true }).click();
  await expect(combatentes.locator('.ini-nome strong')).toHaveText(nomes);
  await expectNoHorizontalOverflow(page);
  await expect(page.locator('[data-sync="salvo"]', { hasText: 'o combate' })).toBeVisible();
  await page.reload(); await navigate(page, 'Iniciativa');
  await expect(page.getByRole('group', { name: 'Combatentes' }).locator('.ini-item')).toHaveCount(5);
  await expect(page.getByLabel('PV de Goblin 2', { exact: true })).toHaveText('PV 4/7');
  await expect(page.getByLabel('PV de Líder goblin', { exact: true })).toHaveText('PV 20/20');
  await expectNoHorizontalOverflow(page);
  await page.getByRole('heading', { name: 'Iniciativa', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('cinco-goblins.png') });
  await info.attach('cinco-goblins', { path: info.outputPath('cinco-goblins.png'), contentType: 'image/png' });
});

test('iniciativa permanece utilizável em três painéis e abre ficha completa', async ({ page }, info) => {
  test.skip((page.viewportSize()?.width ?? 0) < 1024, 'Workspace dividido no desktop.');
  await page.goto('?demo=mestre&nuvem=1');
  await expect(page.getByRole('heading', { name: campaignName, exact: true })).toBeVisible();
  await navigate(page, 'Iniciativa');
  await page.getByLabel('Buscar combatentes', { exact: true }).fill('goblin');
  await page.getByRole('button', { name: 'Adicionar Goblin do Bestiário', exact: true }).click();
  await page.getByRole('button', { name: 'Recolher menu', exact: true }).click();
  await page.getByRole('tab', { name: /^Iniciativa/ }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Abrir em nova coluna à direita', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir ficha completa de Goblin', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Goblin', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: /^Goblin/ }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Abrir em nova coluna à direita', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toHaveCount(3);
  const quantidade = page.getByLabel('Quantidade de dano ou cura de Goblin', { exact: true });
  await quantidade.fill('2'); await page.getByRole('button', { name: 'Causar dano a Goblin', exact: true }).click();
  await expect(page.getByLabel('PV de Goblin', { exact: true })).toHaveText('PV 5/7');
  await page.getByRole('button', { name: 'Lista compacta', exact: true }).click();
  await expectNoHorizontalOverflow(page);
  const bounds = await quantidade.boundingBox(); const painel = await quantidade.locator('xpath=ancestor::*[@role="tabpanel"]').boundingBox();
  expect(bounds).not.toBeNull(); expect(painel).not.toBeNull();
  expect(bounds!.x).toBeGreaterThanOrEqual(painel!.x); expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(painel!.x + painel!.width + 1);
  await page.screenshot({ path: info.outputPath('tres-paineis.png') });
});
